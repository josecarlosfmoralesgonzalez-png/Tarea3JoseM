    private void btnbuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnbuscarActionPerformed
        // TODO add your handling code here:
        String albumBuscado = txtbuscar.getText().trim();
boolean encontrado = false;

if (albumBuscado.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(this, "Ingrese el nombre de un álbum para buscar.");
    return;
}

for (int i = 0; i < totalDiscos; i++) {
    if (titulos[i].equalsIgnoreCase(albumBuscado)) {
        lblanio.setText(String.valueOf(anios[i]));
        encontrado = true;
        break;
    }
}

if (!encontrado) {
    lblanio.setText("—");
    javax.swing.JOptionPane.showMessageDialog(this, "Álbum no encontrado.");
}
    }//GEN-LAST:event_btnbuscarActionPerformed

    private void btnregisActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnregisActionPerformed
        // TODO add your handling code here:
        String albumBuscado = txtbuscar.getText().trim();
String nuevoAnioTexto = txtanio.getText().trim();

if (albumBuscado.isEmpty() || nuevoAnioTexto.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(this, "Complete todos los campos.");
    return;
}

int posicion = -1;
for (int i = 0; i < totalDiscos; i++) {
    if (titulos[i].equalsIgnoreCase(albumBuscado)) {
        posicion = i;
        break;
    }
}

if (posicion != -1) {
    try {
        int nuevoAnio = Integer.parseInt(nuevoAnioTexto);
        anios[posicion] = nuevoAnio;

        java.io.FileWriter writer = new java.io.FileWriter("temp/discos.csv", false);
        for (int i = 0; i < totalDiscos; i++) {
            writer.write(titulos[i] + "," + anios[i] + "\n");
        }
        writer.close();

        lblanio.setText(String.valueOf(nuevoAnio));
        javax.swing.JOptionPane.showMessageDialog(this, "Registro actualizado correctamente.");

    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Ingrese un año válido.");
    }
} else {
    javax.swing.JOptionPane.showMessageDialog(this, "No se encontró el álbum para actualizar.");
}
    }//GEN-LAST:event_btnregisActionPerformed


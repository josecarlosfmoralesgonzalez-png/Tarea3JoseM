    String[] titulos = new String[10];
int[] anios = new int[10];
int totalDiscos = 0;

public void cargarDatos() {
    try {
        java.io.File archivo = new java.io.File("temp/discos.csv");
        if (!archivo.exists()) {
            return;
        }

        java.util.Scanner sc = new java.util.Scanner(archivo);
        totalDiscos = 0;

        while (sc.hasNextLine() && totalDiscos < 10) {
            String linea = sc.nextLine().trim();
            if (!linea.isEmpty()) {
                String[] partes = linea.split(",");
                if (partes.length >= 2) {
                    titulos[totalDiscos] = partes[0].trim();
                    anios[totalDiscos] = Integer.parseInt(partes[1].trim());
                    totalDiscos = totalDiscos + 1;
                }
            }
        }
        sc.close();
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error al cargar los datos.");
    }
}



    private void btncrearcancionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btncrearcancionActionPerformed
        // TODO add your handling code here:
   try {
    String titulo = txttitulo.getText().trim();
    String duracionTexto = txtduracion.getText().trim();
    String genero = txtgenero.getText().trim();
    String artistaCancion = txtartistacancion.getText().trim();

    if (titulo.isEmpty() || duracionTexto.isEmpty() || genero.isEmpty() || artistaCancion.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Complete todos los campos de la canción.");
        return;
    }

    int duracion = Integer.parseInt(duracionTexto);

    Canciones c = new Canciones();
    c.titulo = titulo;
    c.duracionSegundos = duracion;
    c.genero = genero;
    c.nombreArtista = artistaCancion;

    // ESTAS SON LAS LÍNEAS QUE ESCRIBEN EN LA BITÁCORA:
    txtbitacora.append("=== CANCIÓN CREADA ===\n");
    txtbitacora.append("Título: " + c.titulo + "\n");
    txtbitacora.append("Duración: " + c.duracionSegundos + " segundos\n");
    txtbitacora.append("Género: " + c.genero + "\n");
    txtbitacora.append("Artista: " + c.nombreArtista + "\n");
    txtbitacora.append("-----------------------------------\n\n");

    txttitulo.setText("");
    txtduracion.setText("");
    txtgenero.setText("");
    txtartistacancion.setText("");

    javax.swing.JOptionPane.showMessageDialog(this, "Canción creada exitosamente.");

} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(this, "Ingrese un número válido para la duración en segundos.");
}
    }//GEN-LAST:event_btncrearcancionActionPerformed

    private void btncrearartistaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btncrearartistaActionPerformed
        // TODO add your handling code here:
        try {
    String nombre = txtnombreartista.getText().trim();
    String pais = txtpais.getText().trim();
    String oyentesTexto = txtoyentes.getText().trim();

    if (nombre.isEmpty() || pais.isEmpty() || oyentesTexto.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Complete todos los campos del artista.");
        return;
    }

    int oyentes = Integer.parseInt(oyentesTexto);

    Artista a = new Artista();
    a.nombre = nombre;
    a.paisOrigen = pais;
    a.oyentesMensuales = oyentes;

    txtbitacora.append("=== ARTISTA CREADO ===\n");
    txtbitacora.append("Nombre: " + a.nombre + "\n");
    txtbitacora.append("País de origen: " + a.paisOrigen + "\n");
    txtbitacora.append("Oyentes mensuales: " + a.oyentesMensuales + "\n");
    txtbitacora.append("-----------------------------------\n\n");

    txtnombreartista.setText("");
    txtpais.setText("");
    txtoyentes.setText("");

    javax.swing.JOptionPane.showMessageDialog(this, "Artista creado exitosamente.");

} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(this, "Ingrese un número válido para los oyentes.");
}
    }//GEN-LAST:event_btncrearartistaActionPerformed


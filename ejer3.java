    private void btncargarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btncargarActionPerformed
        // TODO add your handling code here:
        try {
    java.io.File archivo = new java.io.File("temp/temperaturas.txt");
    if (!archivo.exists()) {
        javax.swing.JOptionPane.showMessageDialog(this, "El archivo temp/texto.txt no existe.");
        return;
    }

    java.util.Scanner scanner = new java.util.Scanner(archivo);
    StringBuilder sb = new StringBuilder();
    
    while (scanner.hasNextLine()) {
        sb.append(scanner.nextLine()).append("\n");
    }
    scanner.close();

    textoCargado = sb.toString();
    txtresul.setText("--- CONTENIDO DEL ARCHIVO ---\n" + textoCargado);

    javax.swing.JOptionPane.showMessageDialog(this, "Texto cargado exitosamente.");

} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(this, "Error al cargar el archivo.");
}
    }//GEN-LAST:event_btncargarActionPerformed

    private void btncalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btncalcularActionPerformed
        // TODO add your handling code here:
      if (textoCargado.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(this, "Primero debe cargar los datos.");
    return;
}

String[] lineas = textoCargado.trim().split("\n");
double suma = 0;
int diasCalidos = 0;
int diasFrescos = 0;
int totalDias = 0;

for (int i = 0; i < lineas.length; i++) {
    String linea = lineas[i].trim();
    if (!linea.isEmpty()) {
        double temp = Double.parseDouble(linea);
        suma = suma + temp;
        totalDias = totalDias + 1;

        if (temp >= 25.0) {
            diasCalidos = diasCalidos + 1;
        } else {
            diasFrescos = diasFrescos + 1;
        }
    }
}

if (totalDias > 0) {
    double promedio = suma / totalDias;

    txtresul.append("\n--- ANÁLISIS CLIMÁTICO ---\n");
    txtresul.append("Promedio de temperatura: " + String.format("%.2f", promedio) + " °C\n");
    txtresul.append("Días cálidos (>= 25°): " + diasCalidos + "\n");
    txtresul.append("Días frescos (< 25°): " + diasFrescos + "\n");
}
    }//GEN-LAST:event_btncalcularActionPerformed


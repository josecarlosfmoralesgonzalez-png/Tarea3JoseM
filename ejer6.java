    private void btnmostrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnmostrarActionPerformed
        // TODO add your handling code here:
        txtcatalogo.setText("");

if (catalogo.isEmpty()) {
    txtcatalogo.append("El catálogo está vacío.\n");
    return;
}

txtcatalogo.append("=== CATÁLOGO DE VIDEOJUEGOS ===\n\n");

for (int i = 0; i < catalogo.size(); i++) {
    Videojuego vj = catalogo.get(i);
    txtcatalogo.append((i + 1) + ". Título: " + vj.titulo + "\n");
    txtcatalogo.append("   Consola: " + vj.consola + "\n");
    txtcatalogo.append("   Año: " + vj.anioLanzamiento + "\n");
    txtcatalogo.append("-----------------------------------\n");
}

txtcatalogo.append("\nTotal de juegos registrados: " + catalogo.size() + "\n");
    }//GEN-LAST:event_btnmostrarActionPerformed

    private void btnagregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnagregarActionPerformed
        // TODO add your handling code here:
        try {
    String titulo = txttitulo.getText().trim();
    String consola = txtconsola.getText().trim();
    String anioTexto = txtanio.getText().trim();

    if (titulo.isEmpty() || consola.isEmpty() || anioTexto.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Complete todos los campos.");
        return;
    }

    int anio = Integer.parseInt(anioTexto);

    Videojuego vj = new Videojuego(titulo, consola, anio);
    catalogo.add(vj);

    txttitulo.setText("");
    txtconsola.setText("");
    txtanio.setText("");

    javax.swing.JOptionPane.showMessageDialog(this, "Videojuego agregado al catálogo.");

} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(this, "Ingrese un año válido.");
}
    }//GEN-LAST:event_btnagregarActionPerformed

    private void btneliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btneliminarActionPerformed
        // TODO add your handling code here:
        if (catalogo.size() > 0) {
    int ultimoIndice = catalogo.size() - 1;
    Videojuego eliminado = catalogo.remove(ultimoIndice);
    
    javax.swing.JOptionPane.showMessageDialog(this, "Se eliminó el último juego: " + eliminado.titulo);
} else {
    javax.swing.JOptionPane.showMessageDialog(this, "No hay juegos en el catálogo para eliminar.");
}
    }//GEN-LAST:event_btneliminarActionPerformed


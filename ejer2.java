    private void btnagregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnagregarActionPerformed
        // TODO add your handling code here:
        if (indiceTareas < 10) {
    String descripcion = txtdescrip.getText().trim();
    
    if (descripcion.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Por favor, ingrese una descripción para la tarea.");
        return;
    }

    tareas[indiceTareas] = descripcion;
    indiceTareas = indiceTareas + 1;

    txtarea.setText("");
    for (int i = 0; i < indiceTareas; i++) {
        txtarea.append((i + 1) + ". " + tareas[i] + "\n");
    }

    txtdescrip.setText("");
    txtdescrip.requestFocus();

    javax.swing.JOptionPane.showMessageDialog(this, "Tarea agregada correctamente.");

    if (indiceTareas == 10) {
        javax.swing.JOptionPane.showMessageDialog(this, "Llegó al límite máximo de 10 tareas.");
    }
} else {
    javax.swing.JOptionPane.showMessageDialog(this, "No puede agregar más tareas (Límite: 10).");
}
    }//GEN-LAST:event_btnagregarActionPerformed

    private void btnexportarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnexportarActionPerformed
        // TODO add your handling code here:
        if (indiceTareas == 0) {
    javax.swing.JOptionPane.showMessageDialog(this, "No hay tareas registradas para exportar.");
    return;
}

try {
    java.io.File carpeta = new java.io.File("temp");
    if (!carpeta.exists()) {
        carpeta.mkdirs();
    }

    java.io.FileWriter writer = new java.io.FileWriter("temp/breman_tareas_pendientes.txt");
    writer.write("LISTA DE TAREAS PENDIENTES\n");
    writer.write("=========================\n");

    for (int i = 0; i < indiceTareas; i++) {
        writer.write((i + 1) + ". " + tareas[i] + "\n");
    }

    writer.close();

    javax.swing.JOptionPane.showMessageDialog(this, "Tareas exportadas exitosamente.");

} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(this, "Error al exportar las tareas.");
}
    }//GEN-LAST:event_btnexportarActionPerformed


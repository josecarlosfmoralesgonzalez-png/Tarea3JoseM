    private void btnagregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnagregarActionPerformed
        // TODO add your handling code here:
      if (indice < 7) {
    try {
        double kilometros = Double.parseDouble(txtkm.getText());
        rutas[indice] = kilometros;
        indice = indice + 1;

        javax.swing.JOptionPane.showMessageDialog(this, "Ruta agregada.");

        txtkm.setText("");
        txtkm.requestFocus();

        if (indice == 7) {
            javax.swing.JOptionPane.showMessageDialog(this, "Ya ingresó las 7 rutas.");
        }
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Ingrese un número válido.");
    }
} else {
    javax.swing.JOptionPane.showMessageDialog(this, "Ya completó las 7 rutas.");
}
    }//GEN-LAST:event_btnagregarActionPerformed

    private void btnreporteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnreporteActionPerformed
        // TODO add your handling code here:
        if (indice < 7) {
    javax.swing.JOptionPane.showMessageDialog(this, "Faltan rutas por ingresar.");
    return;
}

double total = 0;
for (int i = 0; i < 7; i++) {
    total = total + rutas[i];
}
double promedio = total / 7;

try {
    java.io.File carpeta = new java.io.File("temp");
    if (!carpeta.exists()) {
        carpeta.mkdirs();
    }

    java.io.FileWriter writer = new java.io.FileWriter("temp/breman_reporte_rutas.txt");
    writer.write("Reporte Semanal de Rutas\n");
    writer.write("Total de Kilómetros: " + total + "\n");
    writer.write("Promedio Diario: " + promedio + "\n");
    writer.close();

    javax.swing.JOptionPane.showMessageDialog(this, "Reporte guardado con éxito.");

} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(this, "Error al guardar el archivo.");
}
    }//GEN-LAST:event_btnreporteActionPerformed

